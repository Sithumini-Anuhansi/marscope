"""Train a candidate Mars risk classifier from a reviewed, traceable labeled CSV.

No sample data or labels are generated by this module. Candidate artifacts are
never eligible for API inference until a reviewer approves their manifest.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.inspection import permutation_importance
from sklearn.metrics import confusion_matrix, f1_score, precision_score, recall_score
from sklearn.model_selection import GroupShuffleSplit
from sklearn.pipeline import Pipeline

from app.schemas.risk import FEATURE_UNITS

PROJECT_ROOT = Path(__file__).resolve().parents[3]
MODEL_ROOT = PROJECT_ROOT / "ml-models"
VERSION_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")
REQUIRED_MANIFEST_FIELDS = (
    "dataset_id", "source", "source_url", "citation", "target_column",
    "target_definition", "class_labels", "feature_units", "feature_resolution_km", "feature_sources",
    "spatial_group_column", "observation_time_column",
    "review_status", "reviewed_by", "intended_use", "sha256",
)


class TrainingDataError(ValueError):
    """Raised when a supplied data package is not suitable for training."""


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _read_reviewed_dataset(csv_path: Path, manifest_path: Path) -> tuple[pd.DataFrame, dict[str, Any], list[str]]:
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise TrainingDataError(f"Could not read dataset manifest: {error}") from error
    missing = [field for field in REQUIRED_MANIFEST_FIELDS if not manifest.get(field)]
    if missing:
        raise TrainingDataError(f"Dataset manifest is missing required fields: {', '.join(missing)}")
    if manifest["review_status"] != "approved-for-training":
        raise TrainingDataError("Dataset manifest review_status must be 'approved-for-training'")
    expected_hash = manifest["sha256"]
    if not isinstance(expected_hash, str) or not re.fullmatch(r"[0-9a-fA-F]{64}", expected_hash):
        raise TrainingDataError("Manifest sha256 must be a 64-character hexadecimal digest")
    if expected_hash.lower() != sha256_file(csv_path):
        raise TrainingDataError("CSV SHA-256 does not match the reviewed dataset manifest")
    feature_units = manifest["feature_units"]
    if not isinstance(feature_units, dict) or not feature_units:
        raise TrainingDataError("feature_units must map one or more numeric feature names to units")
    if set(feature_units) - {"terrain_slope", "surface_roughness", "elevation_variation", "temperature", "wind_speed", "dust_opacity"}:
        raise TrainingDataError("Manifest contains unsupported feature names")
    if any(not isinstance(unit, str) or not unit.strip() for unit in feature_units.values()):
        raise TrainingDataError("Every model feature must declare its units")
    if any(unit != FEATURE_UNITS.get(name) for name, unit in feature_units.items()):
        raise TrainingDataError("Feature units must match the risk API contract")
    resolution_ranges = manifest["feature_resolution_km"]
    feature_sources = manifest["feature_sources"]
    if not isinstance(resolution_ranges, dict) or set(resolution_ranges) != set(feature_units):
        raise TrainingDataError("feature_resolution_km must define a min/max range for every feature")
    if not isinstance(feature_sources, dict) or set(feature_sources) != set(feature_units):
        raise TrainingDataError("feature_sources must define allowed source/product pairs for every feature")
    for name, limits in resolution_ranges.items():
        if not isinstance(limits, dict) or not isinstance(limits.get("min"), (int, float)) or not isinstance(limits.get("max"), (int, float)):
            raise TrainingDataError(f"Resolution range for {name} must contain numeric min and max values")
        if not np.isfinite([limits["min"], limits["max"]]).all() or limits["min"] <= 0 or limits["min"] > limits["max"]:
            raise TrainingDataError(f"Resolution range for {name} is invalid")
        if not isinstance(feature_sources[name], list) or not feature_sources[name]:
            raise TrainingDataError(f"Feature {name} needs at least one allowed source/product pair")
        if any(not isinstance(source, dict) or not source.get("source_dataset") or not source.get("source_product_id") for source in feature_sources[name]):
            raise TrainingDataError(f"Every allowed source for {name} needs source_dataset and source_product_id")
    if not isinstance(manifest["class_labels"], list) or any(not isinstance(label, str) or not label.strip() for label in manifest["class_labels"]):
        raise TrainingDataError("class_labels must be a list of non-empty strings")
    if len(set(manifest["class_labels"])) < 2:
        raise TrainingDataError("class_labels must list at least two distinct target classes")
    manifest["class_labels"] = sorted(manifest["class_labels"])

    try:
        frame = pd.read_csv(csv_path)
    except (OSError, UnicodeError, pd.errors.ParserError) as error:
        raise TrainingDataError(f"Could not parse training CSV: {error}") from error
    feature_names = list(feature_units)
    group_column = manifest["spatial_group_column"]
    time_column = manifest["observation_time_column"]
    required_columns = {*feature_names, manifest["target_column"], group_column, "latitude_deg", "longitude_deg", time_column}
    absent = sorted(required_columns - set(frame.columns))
    if absent:
        raise TrainingDataError(f"CSV is missing required columns: {', '.join(absent)}")
    if frame.empty:
        raise TrainingDataError("Training CSV is empty")

    for name in [*feature_names, "latitude_deg", "longitude_deg"]:
        frame[name] = pd.to_numeric(frame[name], errors="coerce")
        if name in {"latitude_deg", "longitude_deg"} and frame[name].isna().any():
            raise TrainingDataError(f"Coordinate column {name} contains missing or nonnumeric values")
        if name in {"latitude_deg", "longitude_deg"} and not np.isfinite(frame[name]).all():
            raise TrainingDataError(f"Coordinate column {name} contains non-finite values")
    if not frame["latitude_deg"].between(-90, 90).all():
        raise TrainingDataError("latitude_deg must use planetocentric degrees in [-90, 90]")
    if not frame["longitude_deg"].between(-180, 360).all():
        raise TrainingDataError("longitude_deg must use positive-east degrees in [-180, 360]")
    frame["longitude_deg"] = (frame["longitude_deg"] + 180.0) % 360.0 - 180.0
    timezone_suffix = re.compile(r"(?:Z|[+-]\d{2}:?\d{2})$", re.IGNORECASE)
    if not frame[time_column].astype(str).map(lambda value: bool(timezone_suffix.search(value.strip()))).all():
        raise TrainingDataError(f"Observation time column {time_column} must contain timezone-aware timestamps")
    timestamps = pd.to_datetime(frame[time_column], errors="coerce", utc=True)
    if timestamps.isna().any():
        raise TrainingDataError(f"Observation time column {time_column} must contain valid timestamps")
    for name in feature_names:
        invalid = frame[name].notna() & ~np.isfinite(frame[name])
        if invalid.any():
            raise TrainingDataError(f"Feature {name} contains an infinite value")
        if frame[name].notna().sum() < 2:
            raise TrainingDataError(f"Feature {name} needs at least two finite observations")
    target = frame[manifest["target_column"]]
    if target.isna().any() or target.astype(str).str.strip().eq("").any():
        raise TrainingDataError("Target labels must be present for every row")
    frame[manifest["target_column"]] = target.astype(str)
    observed_labels = set(frame[manifest["target_column"]].unique())
    declared_labels = set(map(str, manifest["class_labels"]))
    if observed_labels != declared_labels:
        raise TrainingDataError("Observed target labels must exactly match manifest class_labels")
    if frame[group_column].isna().any() or frame[group_column].nunique() < 5:
        raise TrainingDataError("At least five non-empty spatial groups are required for a held-out-region evaluation")
    if frame.groupby(manifest["target_column"])[group_column].nunique().min() < 2:
        raise TrainingDataError("Each target class must occur in at least two spatial groups to evaluate without spatial leakage")
    return frame, manifest, feature_names


def train_candidate(csv_path: str | Path, manifest_path: str | Path, version: str) -> dict[str, Any]:
    """Train one candidate, evaluating on spatially held-out groups only."""
    if not VERSION_PATTERN.fullmatch(version):
        raise TrainingDataError("Version must contain 1–64 letters, numbers, dots, underscores, or hyphens")
    csv_file = Path(csv_path).expanduser().resolve()
    manifest_file = Path(manifest_path).expanduser().resolve()
    frame, dataset_manifest, feature_names = _read_reviewed_dataset(csv_file, manifest_file)
    target_name = dataset_manifest["target_column"]
    group_name = dataset_manifest["spatial_group_column"]
    features = frame[feature_names]
    labels = frame[target_name]
    groups = frame[group_name]

    split = None
    for seed in range(100):
        candidate = next(GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=seed).split(features, labels, groups))
        train_index, test_index = candidate
        train_classes = set(labels.iloc[train_index])
        test_classes = set(labels.iloc[test_index])
        if train_classes == set(dataset_manifest["class_labels"]) and test_classes == set(dataset_manifest["class_labels"]):
            split = train_index, test_index, seed
            break
    if split is None:
        raise TrainingDataError("Could not form a spatially independent 80/20 split containing every class; add reviewed examples across more regions")
    train_index, test_index, split_seed = split
    if set(groups.iloc[train_index]) & set(groups.iloc[test_index]):
        raise TrainingDataError("Spatial leakage detected between training and held-out regions")

    pipeline = Pipeline([
        ("imputer", SimpleImputer(strategy="median", add_indicator=True, keep_empty_features=True)),
        ("classifier", RandomForestClassifier(
            n_estimators=400,
            min_samples_leaf=2,
            class_weight="balanced_subsample",
            random_state=42,
            n_jobs=-1,
        )),
    ])
    pipeline.fit(features.iloc[train_index], labels.iloc[train_index])
    predicted = pipeline.predict(features.iloc[test_index])
    imputer = pipeline.named_steps["imputer"]
    missing_indicator_features = [feature_names[index] for index in imputer.indicator_.features_]
    label_order = sorted(dataset_manifest["class_labels"])
    metrics: dict[str, Any] = {
        "holdout_method": "GroupShuffleSplit; spatial groups are disjoint",
        "holdout_fraction": 0.2,
        "split_seed": split_seed,
        "train_rows": int(len(train_index)),
        "holdout_rows": int(len(test_index)),
        "train_spatial_groups": int(groups.iloc[train_index].nunique()),
        "holdout_spatial_groups": int(groups.iloc[test_index].nunique()),
        "labels": label_order,
        "precision_macro": float(precision_score(labels.iloc[test_index], predicted, labels=label_order, average="macro", zero_division=0)),
        "recall_macro": float(recall_score(labels.iloc[test_index], predicted, labels=label_order, average="macro", zero_division=0)),
        "f1_macro": float(f1_score(labels.iloc[test_index], predicted, labels=label_order, average="macro", zero_division=0)),
        "f1_weighted": float(f1_score(labels.iloc[test_index], predicted, labels=label_order, average="weighted", zero_division=0)),
        "confusion_matrix": confusion_matrix(labels.iloc[test_index], predicted, labels=label_order).tolist(),
        "probability_calibration": "not evaluated; prediction probabilities are not calibrated",
    }
    importance = permutation_importance(
        pipeline, features.iloc[test_index], labels.iloc[test_index],
        n_repeats=10, random_state=42, scoring="f1_macro", n_jobs=-1,
    )
    metrics["global_permutation_importance"] = [
        {"feature": name, "mean_f1_drop": float(score), "std": float(deviation)}
        for name, score, deviation in sorted(
            zip(feature_names, importance.importances_mean, importance.importances_std),
            key=lambda item: item[1], reverse=True,
        )
    ]

    output_dir = MODEL_ROOT / version
    if output_dir.exists():
        raise TrainingDataError(f"Model version already exists: {output_dir}")
    output_dir.mkdir(parents=True, exist_ok=False)
    artifact_path = output_dir / "model.joblib"
    joblib.dump(pipeline, artifact_path, compress=3)
    manifest = {
        "artifact_schema_version": 1,
        "model_version": version,
        "model_family": "RandomForestClassifier",
        "model_file": artifact_path.name,
        "model_sha256": sha256_file(artifact_path),
        "deployment_status": "candidate",
        "trained_at_utc": datetime.now(timezone.utc).isoformat(),
        "training_dataset": {
            "dataset_id": dataset_manifest["dataset_id"],
            "source": dataset_manifest["source"],
            "source_url": dataset_manifest["source_url"],
            "citation": dataset_manifest["citation"],
            "manifest_sha256": sha256_file(manifest_file),
            "csv_sha256": sha256_file(csv_file),
            "review_status": dataset_manifest["review_status"],
            "reviewed_by": dataset_manifest["reviewed_by"],
        },
        "target": {
            "column": target_name,
            "definition": dataset_manifest["target_definition"],
            "class_labels": label_order,
        },
        "features": feature_names,
        "imputation": {
            "method": "training-split median",
            "missing_indicator_features_seen_during_training": missing_indicator_features,
        },
        "feature_units": dataset_manifest["feature_units"],
        "feature_resolution_km": dataset_manifest["feature_resolution_km"],
        "feature_sources": dataset_manifest["feature_sources"],
        "training_feature_ranges": {
            name: {"minimum": float(features[name].min()), "maximum": float(features[name].max())}
            for name in feature_names if features[name].notna().any()
        },
        "training_time_period_utc": {
            "start": timestamps.min().isoformat(),
            "end": timestamps.max().isoformat(),
        },
        "spatial_coverage": {
            "latitude_min": float(frame["latitude_deg"].min()),
            "latitude_max": float(frame["latitude_deg"].max()),
            "longitude_min": float(frame["longitude_deg"].min()),
            "longitude_max": float(frame["longitude_deg"].max()),
            "longitude_convention": "positive-east degrees wrapped to [-180, 180] before training",
        },
        "spatial_group_column": group_name,
        "intended_use": dataset_manifest["intended_use"],
        "evaluation": metrics,
        "probabilities_calibrated": False,
        "score_semantics": "No numeric risk score is exposed; Random Forest probabilities are uncalibrated.",
        "software": {"scikit_learn": sklearn.__version__},
        "approval_note": "Candidate only. Review data, target, spatially held-out metrics, and intended use before changing deployment_status to approved.",
    }
    (output_dir / "model-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Train an MARSCOPE risk model candidate from reviewed labeled data")
    parser.add_argument("--csv", required=True, help="Reviewed CSV with features, coordinates, spatial group, and target")
    parser.add_argument("--manifest", required=True, help="JSON manifest describing target, units, source, review, and CSV SHA-256")
    parser.add_argument("--version", required=True, help="New model version identifier")
    arguments = parser.parse_args()
    print(json.dumps(train_candidate(arguments.csv, arguments.manifest, arguments.version), indent=2))
